-- Esquema PostgreSQL derivado de las entidades JPA en
-- src/main/java/com/com/smm/infrastructure/entities
-- Idempotente: se puede ejecutar varias veces.

CREATE TABLE IF NOT EXISTS categoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255),
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS subcategorias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255),
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS proveedores (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(255),
    contacto VARCHAR(255),
    telefono VARCHAR(255),
    email    VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS productos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    descripcion     TEXT NOT NULL,
    precio          NUMERIC(10,2) NOT NULL,
    subcategoria_id BIGINT REFERENCES subcategorias(id),
    categoria_id    BIGINT REFERENCES categoria(id),
    proveedor_id    BIGINT REFERENCES proveedores(id),
    stock           BIGINT,
    fecha_creacion  DATE DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS imagenes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url         VARCHAR(255),
    descripcion VARCHAR(255),
    producto    INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255),
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS permisos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255),
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS rol_permisos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id     BIGINT NOT NULL REFERENCES roles(id),
    permiso_id BIGINT NOT NULL REFERENCES permisos(id)
);

CREATE TABLE IF NOT EXISTS usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(255),
    email          VARCHAR(255),
    contrasena     VARCHAR(255),
    rol_id         BIGINT,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pedidos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id   INTEGER NOT NULL,
    fecha_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado       BIGINT NOT NULL,
    total        INTEGER NOT NULL,
    direccion    VARCHAR(255) NOT NULL,
    metodo_pago  VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS detalle_pedidos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    producto_id     BIGINT NOT NULL REFERENCES productos(id),
    cantidad        INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS envios (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id              BIGINT REFERENCES pedidos(id),
    fecha_envio            TIMESTAMP,
    fecha_estimada_entrega DATE,
    fecha_entrega          TIMESTAMP(6),
    empresa_envio          VARCHAR(255),
    numero_seguimiento     VARCHAR(100),
    estado                 VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS facturas (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INTEGER REFERENCES pedidos(id),
    total     BIGINT,
    estado    VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS medio_envios (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    costo  VARCHAR(255)
);
